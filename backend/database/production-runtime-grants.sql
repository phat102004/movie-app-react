-- psql <owner connection configured outside argv> -X -v CINEVERSE_GRANT_RUNTIME=true -f backend/database/production-runtime-grants.sql
\set ON_ERROR_STOP on
\if :{?CINEVERSE_GRANT_RUNTIME}
  \if :CINEVERSE_GRANT_RUNTIME
  \else
    \quit 3
  \endif
\else
  \echo 'Stopped: explicit CINEVERSE_GRANT_RUNTIME=true is required.'
  \quit 3
\endif
SELECT current_database() = 'cineverse_prod' AS target_ok \gset
\if :target_ok
\else
  \echo 'Stopped: target must be cineverse_prod.'
  \quit 3
\endif

BEGIN;
-- RUNTIME_GRANTS_BEGIN
DO $$
BEGIN
  IF (SELECT count(*) FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
      JOIN pg_catalog.pg_roles r ON r.oid = c.relowner
      WHERE n.nspname = 'public' AND c.relkind = 'r' AND r.rolname = 'cineverse_migrator'
        AND c.relname IN ('User','Session','PasswordResetToken','Favorite','_prisma_migrations')) <> 5
  THEN RAISE EXCEPTION 'Stopped: expected five migrator-owned tables. DBA must review existing object ownership.';
  END IF;
END $$;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE
  public."User", public."Session", public."PasswordResetToken", public."Favorite"
  TO cineverse_app;
-- RUNTIME_GRANTS_END
COMMIT;

